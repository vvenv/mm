#!/usr/bin/env node
/**
 * Build public/emoji-data.js from emojibase-data (en + zh CLDR).
 * Skips component group and skin-tone variants (keeps base glyphs only).
 *
 *   pnpm emoji:gen
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const en = require("emojibase-data/en/data.json");
const zh = require("emojibase-data/zh/data.json");
const shortcodes = require("emojibase-data/en/shortcodes/emojibase.json");
const messages = require("emojibase-data/en/messages.json");

/** group order index → our tab */
const GROUP_TABS = {
  "smileys-emotion": { id: "smileys", label: "表情" },
  "people-body": { id: "people", label: "人物" },
  "animals-nature": { id: "nature", label: "自然" },
  "food-drink": { id: "food", label: "食物" },
  activities: { id: "activity", label: "活动" },
  "travel-places": { id: "travel", label: "旅行" },
  objects: { id: "objects", label: "物品" },
  symbols: { id: "symbols", label: "符号" },
  flags: { id: "flags", label: "旗帜" },
};

const groupByOrder = new Map(
  messages.groups.map((g) => [g.order, g.key]),
);

const zhByHex = new Map(zh.map((e) => [e.hexcode, e]));

function shortcodeWords(hex) {
  const raw = shortcodes[hex];
  if (!raw) return [];
  const list = Array.isArray(raw) ? raw : [raw];
  return list.map((s) => String(s).replace(/_/g, " "));
}

/** Colloquial extras CLDR often omits (zh + en). */
const EXTRA_KEYWORDS = {
  "💩": "便便 poo shit",
  "❤️": "爱心 红心",
};

function uniqWords(parts) {
  const seen = new Set();
  const out = [];
  for (const part of parts) {
    for (const word of String(part || "")
      .toLowerCase()
      .split(/[\s,]+/)
      .filter(Boolean)) {
      if (seen.has(word)) continue;
      seen.add(word);
      out.push(word);
    }
  }
  return out.join(" ");
}

const buckets = new Map();
for (const tab of Object.values(GROUP_TABS)) {
  buckets.set(tab.id, { ...tab, emojis: [] });
}

const keywords = Object.create(null);
let skippedComponent = 0;

for (const item of en) {
  const groupKey = groupByOrder.get(item.group);
  if (groupKey === "component") {
    skippedComponent++;
    continue;
  }
  const tab = GROUP_TABS[groupKey];
  if (!tab) continue;

  const glyph = item.emoji || item.text;
  if (!glyph) continue;

  // Base only: do not expand item.skins
  buckets.get(tab.id).emojis.push(glyph);

  const z = zhByHex.get(item.hexcode);
  keywords[glyph] = uniqWords([
    z?.label,
    ...(z?.tags || []),
    item.label,
    ...(item.tags || []),
    ...shortcodeWords(item.hexcode),
    EXTRA_KEYWORDS[glyph],
  ]);
}

const categories = [...buckets.values()].filter((c) => c.emojis.length);
const total = categories.reduce((n, c) => n + c.emojis.length, 0);

const header = `/** Auto-generated by scripts/generate-emoji-data.mjs — do not edit. */
`;

const body = `${header}export const EMOJI_CATEGORIES = ${JSON.stringify(categories)};

export const EMOJI_KEYWORDS = ${JSON.stringify(keywords)};
`;

const outPath = join(root, "public", "emoji-data.js");
writeFileSync(outPath, body);

console.log(
  `[emoji:gen] wrote ${outPath} — ${total} glyphs in ${categories.length} tabs (skipped component: ${skippedComponent})`,
);
